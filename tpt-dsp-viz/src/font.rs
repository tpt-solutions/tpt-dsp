#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_five_by_seven() {
        for (c, rows) in GLYPHS {
            assert_eq!(rows.len(), GLYPH_H, "glyph {c:?} height");
            for row in rows {
                assert_eq!(row.len(), GLYPH_W, "glyph {c:?} row {row:?} width");
            }
        }
    }

    #[test]
    fn no_duplicate_characters() {
        for (i, (a, _)) in GLYPHS.iter().enumerate() {
            assert!(
                GLYPHS[i + 1..].iter().all(|(b, _)| a != b),
                "duplicate glyph {a:?}"
            );
        }
    }

    #[test]
    fn ui_labels_are_fully_supported() {
        // Every character the visualizer can print must have a real glyph,
        // not the `?` fallback.
        let labels = [
            "Source: ",
            "Peak: ",
            " Hz, ",
            " dB",
            "Pause",
            "Resume",
            "Rows: ",
            "synthetic (multi-tone + noise)",
            "audio input (built-in WASAPI/native backend)",
            "custom synthetic source",
            "0 dB",
            "-120 dB",
            "0123456789.-+",
        ];
        for label in labels {
            for c in label.chars() {
                let found = GLYPHS.iter().any(|(g, _)| *g == c);
                assert!(found, "no glyph for {c:?} in {label:?}");
            }
        }
    }

    #[test]
    fn text_width_counts_gaps_between_glyphs_only() {
        assert_eq!(text_width(""), 0);
        assert_eq!(text_width("A"), GLYPH_W);
        assert_eq!(text_width("AB"), 2 * GLYPH_W + 1);
    }
}
