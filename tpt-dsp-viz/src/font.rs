//! Built-in 5x7 bitmap font for the visualizer's labels.
//!
//! Each glyph is seven rows of five columns. A `#` marks a lit pixel; any other
//! byte is background. The font covers ASCII letters, digits and the
//! punctuation the UI uses. Unsupported characters draw as `?`.

/// Width of a glyph in pixels.
pub(crate) const GLYPH_W: usize = 5;
/// Height of a glyph in pixels.
pub(crate) const GLYPH_H: usize = 7;
/// Horizontal distance from one glyph origin to the next (one pixel gap).
pub(crate) const ADVANCE: usize = GLYPH_W + 1;

/// One glyph: seven rows, each exactly [`GLYPH_W`] bytes.
pub(crate) type Glyph = [&'static str; GLYPH_H];

const UNKNOWN: Glyph = [
    " ### ", "#   #", "    #", "   # ", "  #  ", "     ", "  #  ",
];

const BLANK: Glyph = ["     "; GLYPH_H];

/// Pixel rows for `c`, falling back to `?` for characters outside the font.
pub(crate) fn glyph(c: char) -> &'static Glyph {
    GLYPHS
        .iter()
        .find(|(ch, _)| *ch == c)
        .map(|(_, g)| g)
        .unwrap_or(&UNKNOWN)
}

/// Width in pixels of `s` when drawn at scale 1 (no trailing gap).
pub(crate) fn text_width(s: &str) -> usize {
    let n = s.chars().count();
    if n == 0 {
        0
    } else {
        n * ADVANCE - 1
    }
}

